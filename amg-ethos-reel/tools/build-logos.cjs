// Collect traced logo SVGs (tools/*.svg) into src/logoPaths.ts so the logos
// render as inline, recolorable vector paths inside the Remotion composition.
const fs = require('fs');
const path = require('path');
const names = { amgWord: 'amg-word', ethosWord: 'ethos-word', ethosMark: 'ethos-mark' };
let out = '// Generated by tools/build-logos.cjs from tools/*.svg — do not edit by hand.\n\n';
for (const [key, file] of Object.entries(names)) {
  const svg = fs.readFileSync(path.join(__dirname, file + '.svg'), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1].replace(/\s+/g, ' ').trim());
  out += `export const ${key} = ${JSON.stringify({ viewBox, d: ds.join(' ') })};\n`;
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'logoPaths.ts'), out);
console.log('wrote src/logoPaths.ts');
