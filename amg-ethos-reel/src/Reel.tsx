import React from 'react';
import { AbsoluteFill, Audio, Sequence, staticFile } from 'remotion';
import './fonts';
import { CircleWipe, SceneOut } from './components/Kit';
import { C, T } from './theme';
import { Hook } from './scenes/Hook';
import { Lockup } from './scenes/Lockup';
import { Headline } from './scenes/Headline';
import { Product } from './scenes/Product';
import { Family } from './scenes/Family';
import { Cta } from './scenes/Cta';
import { EndCard } from './scenes/EndCard';

type Scene = { key: keyof typeof T; el: React.ReactNode; wipe?: { x: number; y: number; ring?: string } };

// Each scene enters through a brand-circle wipe that starts where the eye
// already is (the AMG mark, the "+" badge, the phone, the button…).
const SCENES: Scene[] = [
  { key: 'hook', el: <Hook /> },
  { key: 'lockup', el: <Lockup />, wipe: { x: 540, y: 480 } },
  { key: 'headline', el: <Headline />, wipe: { x: 540, y: 880, ring: C.lime } },
  { key: 'product', el: <Product />, wipe: { x: 980, y: 1600 } },
  { key: 'family', el: <Family />, wipe: { x: 540, y: 1100 } },
  { key: 'cta', el: <Cta />, wipe: { x: 120, y: 260 } },
  { key: 'end', el: <EndCard />, wipe: { x: 540, y: 1080 } },
];

export const Reel: React.FC = () => (
  <AbsoluteFill style={{ background: C.ink }}>
    {/* Original sound design, generated by tools/sound.py. Render with --muted for a silent cut. */}
    <Audio src={staticFile('soundtrack.wav')} />
    {SCENES.map(({ key, el, wipe }) => {
      const { from, dur } = T[key];
      const body = key === 'end' ? el : <SceneOut dur={dur}>{el}</SceneOut>;
      return (
        <Sequence key={key} from={from} durationInFrames={dur} name={key}>
          {wipe ? (
            <CircleWipe x={wipe.x} y={wipe.y} ring={wipe.ring}>
              {body}
            </CircleWipe>
          ) : (
            body
          )}
        </Sequence>
      );
    })}
  </AbsoluteFill>
);
